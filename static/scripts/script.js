//---------------------------Script to make only that section visible which is clicked by user--------------------------
let navLinks = document.querySelectorAll('nav a');
// console.log("selected", navLinks)
let sections = document.querySelectorAll('section');
// console.log("selected", sections)
navLinks.forEach(link => {
    link.addEventListener('click', e => {
        e.preventDefault();
        const targetId = link.getAttribute('href');
        const targetSection = document.querySelector(targetId);

        sections.forEach(section => {
            section.classList.remove('active');
        });

        targetSection.classList.add('active');
    });
});
//---------------------------Script to style active anchor link differently in navbar--------------------------
// Get all anchor tags in navbarDownload
const navLinks1 = document.querySelectorAll('.Navigate .nav-link');
// console.log("selected", navLinks1);

// Add click event listener to document
document.addEventListener('click', (event) => {
    // Check if clicked element is an anchor tag
    if (event.target.matches('a')) {
        // Check if clicked anchor tag is in navbar
        if (event.target.closest('.Navigate') !== null) {
            // Remove active class from all anchor tags in navbar
            navLinks1.forEach((link) => {
                link.classList.remove('active');
            });
            // Add active class to clicked anchor tag
            event.target.classList.add('active');
            // Prevent default link behavior
            event.preventDefault();
        }
    }
});
// Add "active" class to first anchor tag by default
navLinks[0].classList.add('active');

